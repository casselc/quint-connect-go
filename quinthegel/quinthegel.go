// Package quinthegel combines Hegel's property-based and state-machine
// testing (hegel.dev/go/hegel) with Quint models, in both directions:
//
//  1. Hegel drives, the model judges. A Hegel state machine (or any Hegel
//     test) exercises the implementation; the model steps it performs are
//     recorded (explicitly with Recorder.Step, or by //quint:action code
//     woven with Orchestrion) and checked against the Quint model through
//     a binding: every step must be a transition of the model, the
//     observed state must match, and the model's invariants must hold.
//     Checked per test case (Each), a violation is an ordinary Hegel
//     failure, so Hegel shrinks the run to a minimal trace the model
//     rejects. Checked after the test (After), runs are validated in
//     parallel at the end, which is cheaper but does not shrink.
//
//  2. The model drives, Hegel varies. Traces generated by Quint (`quint run
//     --mbt`) are replayed through a connect.Driver inside a Hegel test
//     (Replay): Hegel picks the trace and how much of it to run, and the
//     driver can draw the concrete details the model abstracts away
//     (payload bytes, timings, which goroutine goes first). A failure
//     shrinks to the shortest prefix of the simplest trace, with the
//     simplest concrete details.
//
// Both directions use the same model, so a design property checked by
// `quint run --invariant` is also checked on the code, and a Hegel
// counterexample can be replayed against the model to tell an
// implementation bug (the run does not conform) from a design bug (the run
// conforms and violates a model invariant).
package quinthegel

import (
	"context"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"sync"
	"testing"
	"time"

	"github.com/casselc/quint-connect-go/qobs"
	"github.com/casselc/quint-connect-go/qtrace"
	"github.com/casselc/quint-connect-go/validate"
	"hegel.dev/go/hegel"
)

// Recorder records the model steps of one Hegel test case. Each recorded
// step is also a Hegel note, so a shrunk counterexample prints as the
// sequence of model actions it took.
type Recorder struct {
	*qobs.Recorder
	tc  hegel.TestCase
	mem *qobs.MemorySink
	n   int
	mu  sync.Mutex
}

// NewRecorder returns a recorder for the test case tc. opts configure the
// underlying qobs.Recorder (e.g. qobs.WithActor).
func NewRecorder(tc hegel.TestCase, opts ...qobs.Option) *Recorder {
	mem := &qobs.MemorySink{}
	r := &Recorder{tc: tc, mem: mem}
	r.Recorder = qobs.NewRecorder(qobs.Tee{mem, noteSink{r}}, opts...)
	return r
}

type noteSink struct{ r *Recorder }

func (n noteSink) Record(_ context.Context, s *qtrace.Step) {
	n.r.mu.Lock()
	n.r.n++
	i := n.r.n
	n.r.mu.Unlock()
	n.r.tc.Note(fmt.Sprintf("model step %d: %s", i, s.String()))
}

// Step records one model step: the action, the implementation's error (its
// outcome), and alternating keys and values (see qobs.Recorder.Record):
// arguments, "obs.<name>" observations of the state after the step, and
// identity overrides.
func (r *Recorder) Step(action string, err error, kv ...any) {
	r.Record(context.Background(), action, err, kv...)
}

// Steps returns what was recorded so far.
func (r *Recorder) Steps() []qtrace.Step { return r.mem.Steps() }

// Install makes r the global qobs recorder until the returned function is
// called, so code woven with Orchestrion (//quint:action) records into it.
// Hegel runs test cases one at a time, so one global recorder per case is
// safe; with hegel.WithConcurrency the rules of one case share it.
func (r *Recorder) Install() (restore func()) {
	prev := qobs.Global()
	qobs.SetGlobal(r.Recorder)
	return func() { qobs.SetGlobal(prev) }
}

// Mode says when recorded runs are checked against the model.
type Mode int

const (
	// Each checks every test case as it finishes, failing it on a
	// violation: Hegel then shrinks the run against the model. Every check
	// is one `quint test` process (about half a second with the Rust
	// backend), and shrinking runs many, so keep test-case counts modest.
	Each Mode = iota
	// After collects the runs (distinct ones only) and checks them all
	// in bulk when the Hegel test is over (validate.Checker.CheckBatch:
	// one quint process per instance and chunk). A violation fails the Go
	// test with the run's steps, unshrunk; Hegel's own failures still shrink.
	After
	// Batched generates a round of test cases without checking them,
	// checks the round in bulk (as After), and continues with another
	// round (Rounds, Budget) while every run passes. When one fails, it
	// replays the round with the same seed in Each mode: the cached bulk
	// verdicts decide every case up to the failing one without quint, and
	// Hegel shrinks the failure against the model. Bulk speed while the
	// runs pass; Each's shrinking when one does not. The test body must be
	// deterministic given Hegel's draws (as for any shrinking).
	Batched
	// Off records but does not check (e.g. for runs whose steps are
	// inspected by hand, or checked elsewhere).
	Off
)

// Config of a model-checked Hegel test.
type Config struct {
	// Binding is the path of the binding file mapping recorded steps to
	// the model's actions (see package binding).
	Binding string
	Mode    Mode
	// Validate configures quint (binary, backend). Dir is ignored: see Keep.
	Validate validate.Options
	// Recorder options for each test case's recorder, e.g. qobs.WithActor.
	Recorder []qobs.Option
	// Global installs each case's recorder as the global qobs recorder,
	// for code woven with Orchestrion.
	Global bool
	// Keep is where the generated Quint modules, step logs and ITF go
	// (default $QUINTGO_KEEP/<test>, else t.TempDir()). The module of a
	// failing run is a Quint regression test of it: `quint test` it.
	Keep string
	// AllowEmpty accepts test cases that record no steps.
	AllowEmpty bool
	// Parallel bounds concurrent quint processes in After mode (0: GOMAXPROCS).
	Parallel int
	// Batched mode: the number of rounds (default 1), each of the test
	// cases hegel.WithTestCases asks for, with its own seed; and an
	// optional time budget that stops starting rounds once exceeded.
	Rounds int
	Budget time.Duration
	// Seed of the first round (later rounds add 1 each); 0: random. The
	// seed of a failing round is logged, to reproduce it.
	Seed int64
}

// Test runs a Hegel test whose cases record model steps, and checks the
// runs against the model as cfg.Mode says. body gets the Hegel test case
// and its recorder; it typically builds the system under test and calls
// hegel.RunStateful on a machine whose rules call rec.Step.
//
//	quinthegel.Test(t, quinthegel.Config{Binding: "testdata/bank.yaml"}, func(ht *hegel.T, rec *quinthegel.Recorder) {
//		hegel.RunStateful(ht, &bankMachine{bank: NewBank(), rec: rec})
//	}, hegel.WithTestCases(30))
func Test(t *testing.T, cfg Config, body func(ht *hegel.T, rec *Recorder), opts ...hegel.Option) {
	t.Helper()
	if cfg.Mode == Batched {
		batched(t, cfg, body, opts)
		return
	}
	keep := keepDir(t, cfg.Keep)
	var checker *validate.Checker
	var cc *CaseChecker
	if cfg.Mode != Off {
		vo := cfg.Validate
		vo.Dir = filepath.Join(keep, "quint")
		c, err := Checker(cfg.Binding, vo)
		if err != nil {
			t.Fatalf("quinthegel: %v", err)
		}
		checker = c
		cc = NewCaseChecker(c)
	}
	var (
		mu   sync.Mutex
		runs [][]qtrace.Step
		seen = map[string]bool{}
	)
	if cfg.Mode == Each {
		// every case runs quint: Hegel's "too slow" health check would
		// abort the search (a later SuppressHealthCheck in opts wins)
		opts = append([]hegel.Option{hegel.SuppressHealthCheck(hegel.TooSlow)}, opts...)
	}
	hegel.Test(t, func(ht *hegel.T) {
		rec := NewRecorder(ht, cfg.Recorder...)
		if cfg.Global {
			defer rec.Install()()
		}
		body(ht, rec)
		steps := rec.Steps()
		if len(steps) == 0 {
			if !cfg.AllowEmpty {
				ht.Fatalf("quinthegel: the test case recorded no model steps (set AllowEmpty if that is expected)")
			}
			return
		}
		switch cfg.Mode {
		case Each:
			CheckCase(ht, cc, steps)
		case After:
			key := stepsKey(steps)
			mu.Lock()
			if !seen[key] {
				seen[key] = true
				runs = append(runs, steps)
			}
			mu.Unlock()
		}
	}, opts...)
	if cfg.Mode == Each {
		q, hits := cc.Stats()
		t.Logf("quinthegel: %d runs checked with quint, %d decided from earlier verdicts", q, hits)
	}
	if cfg.Mode == After && len(runs) > 0 {
		CheckAll(t, checker, runs, cfg.Parallel)
	}
}

// CheckAll validates runs in parallel and fails t, listing each violating
// run's steps and verdict.
func CheckAll(t testing.TB, c *validate.Checker, runs [][]qtrace.Step, parallel int) []*validate.Report {
	t.Helper()
	reps, errs := c.CheckBatch(context.Background(), runs, 0)
	bad := 0
	for i, rep := range reps {
		switch {
		case errs[i] != nil:
			bad++
			t.Errorf("quinthegel: run %d: %v\n%s", i, errs[i], Render(runs[i]))
		case !rep.OK():
			bad++
			t.Errorf("quinthegel: run %d does not satisfy the model:\n%s\nsteps:\n%s", i, rep.Summary(), Render(runs[i]))
		}
	}
	t.Logf("quinthegel: checked %d distinct runs against the model, %d violations", len(runs), bad)
	return reps
}

// Render lists steps one per line, for failure messages, marking where the
// process (incarnation) changes: where a binding's restart action goes.
func Render(steps []qtrace.Step) string {
	var b strings.Builder
	procs := ids{}
	for i, s := range steps {
		p := procs.of(s.Process)
		if i > 0 && s.Process != steps[i-1].Process {
			fmt.Fprintf(&b, "  -- process %d (restart)\n", p)
		}
		fmt.Fprintf(&b, "  [%d] %s\n", i, s.String())
	}
	return b.String()
}

func stepsKey(steps []qtrace.Step) string {
	var b strings.Builder
	procs, threads := ids{}, ids{}
	for i := range steps {
		b.WriteString(stepKey(&steps[i], procs, threads))
		fmt.Fprintf(&b, "%v;", steps[i].Order)
	}
	return b.String()
}

var checkers sync.Map

// Checker returns a validate.Checker for a binding, typechecking the model
// once per test binary and options.
func Checker(bindingPath string, o validate.Options) (*validate.Checker, error) {
	abs, err := filepath.Abs(bindingPath)
	if err != nil {
		return nil, err
	}
	key := abs + "|" + o.Quint + "|" + o.Backend
	if c, ok := checkers.Load(key); ok {
		cc := *c.(*validate.Checker)
		cc.Options.Dir = o.Dir
		return &cc, nil
	}
	c, err := validate.NewChecker(abs, o)
	if err != nil {
		return nil, err
	}
	checkers.Store(key, c)
	cc := *c
	return &cc, nil
}

func keepDir(t testing.TB, dir string) string {
	if dir != "" {
		return dir
	}
	if k := os.Getenv("QUINTGO_KEEP"); k != "" {
		return filepath.Join(k, strings.NewReplacer("/", "_", " ", "_").Replace(t.Name()))
	}
	return t.TempDir()
}

// batched is Test in Batched mode.
func batched(t *testing.T, cfg Config, body func(ht *hegel.T, rec *Recorder), opts []hegel.Option) {
	t.Helper()
	keep := keepDir(t, cfg.Keep)
	vo := cfg.Validate
	vo.Dir = filepath.Join(keep, "quint")
	c, err := Checker(cfg.Binding, vo)
	if err != nil {
		t.Fatalf("quinthegel: %v", err)
	}
	cc := NewCaseChecker(c)
	rounds := cfg.Rounds
	if rounds <= 0 {
		rounds = 1
	}
	seed := cfg.Seed
	if seed == 0 {
		seed = time.Now().UnixNano() & 0x7fffffff
	}
	start := time.Now()
	record := func(ht *hegel.T) []qtrace.Step {
		rec := NewRecorder(ht, cfg.Recorder...)
		if cfg.Global {
			defer rec.Install()()
		}
		body(ht, rec)
		steps := rec.Steps()
		if len(steps) == 0 && !cfg.AllowEmpty {
			ht.Fatalf("quinthegel: the test case recorded no model steps (set AllowEmpty if that is expected)")
		}
		return steps
	}
	total := 0
	for r := 0; r < rounds; r++ {
		if cfg.Budget > 0 && r > 0 && time.Since(start) > cfg.Budget {
			t.Logf("quinthegel: time budget %v used after %d rounds", cfg.Budget, r)
			break
		}
		s := seed + int64(r)
		// 1. Generate a round, recording each case's run, checking nothing.
		var mu sync.Mutex
		var runs [][]qtrace.Step
		seen := map[string]bool{}
		hegel.Test(t, func(ht *hegel.T) {
			steps := record(ht)
			key := stepsKey(steps)
			mu.Lock()
			defer mu.Unlock()
			if !seen[key] {
				seen[key] = true
				runs = append(runs, steps)
			}
		}, append(append([]hegel.Option(nil), opts...), hegel.WithSeed(s), hegel.WithPhases(hegel.PhaseGenerate))...)
		if t.Failed() {
			return // the body's own checks failed, and Hegel shrank that already
		}
		// 2. Check the round in bulk.
		vs, err := cc.Prefetch(context.Background(), runs)
		if err != nil {
			t.Fatalf("quinthegel: checking round %d: %v", r, err)
		}
		total += len(runs)
		var failed []int
		for i, v := range vs {
			if !v.OK {
				failed = append(failed, i)
			}
		}
		if len(failed) == 0 {
			continue
		}
		// 3. A run failed: replay the round, now checking each case. The
		// verdicts are cached, so only Hegel's shrink candidates run quint.
		t.Logf("quinthegel: round %d (seed %d): %d of %d runs violate the model; shrinking", r, s, len(failed), len(runs))
		ok := t.Run("shrink", func(st *testing.T) {
			hegel.Test(st, func(ht *hegel.T) {
				CheckCase(ht, cc, record(ht))
			}, append(append([]hegel.Option{hegel.SuppressHealthCheck(hegel.TooSlow)}, opts...), hegel.WithSeed(s))...)
		})
		if ok {
			// The replay did not meet the failing case again (generation was
			// not reproducible): report the bulk failure, unshrunk.
			i := failed[0]
			t.Errorf("quinthegel: run %d of round %d (seed %d) does not satisfy the model (not shrunk):\n%s\nsteps:\n%s",
				i, r, s, vs[i].Summary, Render(runs[i]))
		}
		q, hits := cc.Stats()
		t.Logf("quinthegel: %d distinct runs in %d rounds; ~%d quint processes, %d verdicts from the cache", total, r+1, q, hits)
		return
	}
	q, hits := cc.Stats()
	t.Logf("quinthegel: %d distinct runs in bulk, all satisfy the model (~%d quint processes, %d verdicts from the cache, %v)",
		total, q, hits, time.Since(start).Round(time.Millisecond))
}
